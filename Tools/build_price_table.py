#!/usr/bin/env python3
"""Generates Assets/Scripts/Core/Economy/RegionalPriceTable.cs from World Bank data.

Inputs (World Bank API, CC BY 4.0):
  countries.json : https://api.worldbank.org/v2/country?format=json&per_page=400
  gdppc.json     : https://api.worldbank.org/v2/country/all/indicator/NY.GDP.PCAP.CD?format=json&mrnev=1&per_page=1000

multiplier = clamp((GDP per capita / US GDP per capita) ^ ELASTICITY, FLOOR, 1.0)
An elasticity around 0.35 tracks how consumer price levels actually scale with income
(Balassa-Samuelson), so poorer countries get a real discount without prices collapsing.
"""
import json, sys

ELASTICITY, FLOOR = 0.35, 0.20

def main(countries_path, gdp_path, out_path):
    _, cs = json.load(open(countries_path))
    real = {c["id"]: c for c in cs if c["region"]["value"].strip() != "Aggregates"}
    meta, rows = json.load(open(gdp_path))
    gdp = {}
    for r in rows:
        c = real.get(r["countryiso3code"])
        if c and r["value"] is not None:
            gdp[c["iso2Code"]] = (int(r["date"]), r["value"])
    us = gdp["US"][1]
    entries = []
    for code in sorted(gdp):
        m = max(FLOOR, min(1.0, (gdp[code][1] / us) ** ELASTICITY))
        entries.append(f"{code}:{m:.2f}")
    lines = []
    for i in range(0, len(entries), 12):
        lines.append('            "' + ",".join(entries[i:i + 12]) + ',"')
    body = "\n            + ".join(l.strip() for l in lines)
    cs_src = f'''// <auto-generated>
// Generated by Tools/build_price_table.py - do not edit by hand, re-run the script instead.
// Source: World Bank WDI, GDP per capita (current US$), NY.GDP.PCAP.CD, last updated {meta.get("lastupdated")} (CC BY 4.0).
// multiplier = clamp((country GDP per capita / US GDP per capita)^{ELASTICITY}, {FLOOR}, 1.0)
// </auto-generated>
namespace Casino.Core.Economy
{{
    internal static class RegionalPriceTable
    {{
        public const string DataSource = "World Bank GDP per capita (NY.GDP.PCAP.CD), updated {meta.get("lastupdated")}";

        // ISO 3166-1 alpha-2 : price multiplier relative to the base (USD) price.
        public const string Data =
            {body};
    }}
}}
'''
    open(out_path, "w").write(cs_src)
    print(f"{len(entries)} countries -> {out_path}")

if __name__ == "__main__":
    main(*sys.argv[1:4])
